/// WHO Child Growth Standards (2006) for 0–24 months as LMS parameters
/// per completed month, from the WHO tables published by the CDC
/// (ftp.cdc.gov/pub/Health_Statistics/NCHS/growthcharts, WHO-*-Percentiles).
///
/// value(z) = M · (1 + L·S·z)^(1/L); percentile 3 ≈ z −1.881, 97 ≈ +1.881.
library;

import 'dart:math' as math;

enum GrowthMeasure { weight, length, head }

enum ChildSex { female, male }

class Lms {
  const Lms(this.l, this.m, this.s);

  final double l;
  final double m;
  final double s;

  double valueAt(double z) =>
      l == 0 ? m * math.exp(s * z) : m * math.pow(1 + l * s * z, 1 / l);

  /// Standard deviation score of [value].
  double zScore(double value) =>
      l == 0 ? math.log(value / m) / s : (math.pow(value / m, l) - 1) / (l * s);
}

/// LMS at [months] (0–24, interpolated), or null outside the range.
Lms? growthReference(ChildSex sex, GrowthMeasure measure, double months) {
  if (months < 0 || months > 24) return null;
  final table = _tables[sex]![measure]!;
  final i = months.floor().clamp(0, 23);
  final f = months - i;
  final a = table[i];
  final b = table[i + 1];
  double lerp(double x, double y) => x + (y - x) * f;
  return Lms(lerp(a.l, b.l), lerp(a.m, b.m), lerp(a.s, b.s));
}

/// Percentile (0–100) of [value], via the normal distribution.
double growthPercentile(Lms lms, double value) {
  final z = lms.zScore(value);
  return 100 * _normalCdf(z);
}

double _normalCdf(double z) {
  // Abramowitz–Stegun 7.1.26, accurate to about 1e-7.
  final t = 1 / (1 + 0.3275911 * z.abs() / math.sqrt2);
  final y =
      1 -
      (((((1.061405429 * t - 1.453152027) * t) + 1.421413741) * t -
                      0.284496736) *
                  t +
              0.254829592) *
          t *
          math.exp(-z * z / 2);
  return z >= 0 ? (1 + y) / 2 : (1 - y) / 2;
}

